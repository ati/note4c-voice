#!/usr/bin/env python3
"""Bake OFL Noto Sans into 1-bit proportional glyphs; no runtime font dependency."""
from pathlib import Path
import math
from PIL import Image, ImageDraw, ImageFont

root = Path(__file__).resolve().parents[1]
points = sorted(set(range(32, 127)) | set(range(0x400, 0x460))
                | {0xa0, 0xb0, 0xb7, 0x2013, 0x2014, 0x2018, 0x2019, 0x201c, 0x201d, 0x2026, 0xfffd})
output = ['// Generated by tools/generate_fonts.py. Noto Sans: SIL OFL 1.1.', '#include "font.h"', 'namespace {']

def bake(name, size, weight):
    font = ImageFont.truetype(str(root / 'assets' / f'NotoSans-{weight}.ttf'), size)
    bounds = [font.getbbox(chr(cp), anchor='ls') for cp in points]
    baseline = max(-b[1] for b in bounds)
    line_height = baseline + max(b[3] for b in bounds) + 2
    data, glyphs = [], []
    for cp, (left, top, right, bottom) in zip(points, bounds):
        width, height = right - left, bottom - top
        glyphs.append(f'{{{cp},{len(data)},{width},{height},{math.ceil(font.getlength(chr(cp)))},{left},{top}}}')
        if width and height:
            image = Image.new('L', (width, height))
            ImageDraw.Draw(image).text((-left, -top), chr(cp), font=font, fill=255, anchor='ls')
            for y in range(height):
                for start in range(0, width, 8):
                    byte = 0
                    for bit in range(8):
                        if start + bit < width and image.getpixel((start + bit, y)) >= 128:
                            byte |= 0x80 >> bit
                    data.append(byte)
    output.append(f'const uint8_t {name}Bits[] = {{')
    for i in range(0, len(data), 32): output.append(','.join(map(str, data[i:i+32])) + ',')
    output.extend(['};', f'const Glyph {name}Glyphs[] = {{' + ','.join(glyphs) + '};'])
    return f'{{{size},{line_height},{baseline},{name}Glyphs,{len(points)},{name}Bits}}'

body = [bake('body'+str(size), size, 'SemiBold') for size in range(38, 11, -2)]
small = bake('small', 10, 'SemiBold')
stamp = bake('stamp', 16, 'Regular')
output.extend(['}', 'const Font bodyFonts[] = {' + ','.join(body) + '};',
               'const size_t bodyFontCount = sizeof(bodyFonts) / sizeof(bodyFonts[0]);',
               'const Font smallFont = ' + small + ';', 'const Font stampFont = ' + stamp + ';',
               'const Font timeFont = ' + body[(38 - 30) // 2] + ';'])
(root / 'src/fonts.cpp').write_text('\n'.join(output) + '\n')
print('Generated fonts.cpp:', (root / 'src/fonts.cpp').stat().st_size, 'bytes of source')
